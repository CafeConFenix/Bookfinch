"""Regenerate every logo asset from the single source of truth, assets/logo.svg.

Outputs:
  assets/bookfinch.ico   multi-size Windows icon (used by the PyInstaller specs)
  assets/logo-512.png    general-purpose PNG logo
  bookfinch/icon.py      64x64 PNG (base64) used as the window icon

Developer tool only. The generated files are committed, so building or running the app never needs this.
Requires Playwright (Chromium renders the SVG):

    pip install playwright && playwright install chromium
    python tools/make_icon.py
"""
import base64
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG = os.path.join(ROOT, "assets", "logo.svg")
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)


def render_all(sizes):
    """Return {size: PNG bytes} with a transparent background."""
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        sys.exit("Playwright is required:  pip install playwright && playwright install chromium")
    with open(SVG, encoding="utf-8") as f:
        markup = f.read()
    out = {}
    with sync_playwright() as p:
        browser = p.chromium.launch()
        for size in sorted(set(sizes)):
            page = browser.new_page(viewport={"width": size, "height": size})
            svg = markup.replace('width="512" height="512"', 'width="%d" height="%d"' % (size, size))
            page.set_content("<html><body style='margin:0;background:transparent'>%s</body></html>" % svg)
            out[size] = page.screenshot(omit_background=True)
            page.close()
        browser.close()
    return out


def make_ico(pngs):
    """Pack PNG images into an .ico container (PNG-compressed entries, Windows Vista+)."""
    sizes = sorted(pngs)
    head = struct.pack("<HHH", 0, 1, len(sizes))
    entries, blobs, offset = b"", b"", 6 + 16 * len(sizes)
    for s in sizes:
        data = pngs[s]
        entries += struct.pack("<BBBBHHII", s % 256, s % 256, 0, 0, 1, 32, len(data), offset)
        blobs += data
        offset += len(data)
    return head + entries + blobs


def make_icon_py(png):
    b64 = base64.b64encode(png).decode("ascii")
    lines = ['    "%s"' % b64[i:i + 76] for i in range(0, len(b64), 76)]
    return ('"""Window icon (64x64 PNG, base64). Generated by tools/make_icon.py."""\n'
            "ICON_PNG_B64 = (\n" + "\n".join(lines) + "\n)\n")


def main():
    pngs = render_all(set(ICO_SIZES) | {64, 512})
    with open(os.path.join(ROOT, "assets", "bookfinch.ico"), "wb") as f:
        f.write(make_ico({s: pngs[s] for s in ICO_SIZES}))
    with open(os.path.join(ROOT, "assets", "logo-512.png"), "wb") as f:
        f.write(pngs[512])
    with open(os.path.join(ROOT, "bookfinch", "icon.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(make_icon_py(pngs[64]))
    print("Generated assets/bookfinch.ico, assets/logo-512.png and bookfinch/icon.py")


if __name__ == "__main__":
    main()
